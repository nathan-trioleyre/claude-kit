def read_kit_version(kit: Path) -> str:
    vf = kit / "VERSION"
    return vf.read_text(encoding="utf-8").strip() if vf.is_file() else "0.0.0"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def unsafe_permission(rule: str) -> str | None:
    """Return a reason if a profile/org permission rule is too broad, else None."""
    if rule in DISALLOWED_PERMISSIONS:
        return f"unsafe permission '{rule}' is forbidden"
    m = re.fullmatch(r"Bash\((.*)\)", rule)
    if m:
        body = m.group(1).strip()
        first = body.split(" ", 1)[0].split(":", 1)[0].lower()
        if first.endswith(".exe"):
            first = first[:-4]
        if first.startswith("*"):
            return f"permission '{rule}' starts with a wildcard"
        if first in UNSAFE_BASH_COMMANDS:
            return f"permission '{rule}' allows arbitrary code execution or destructive commands ('{first}')"
    return None


def resolve_kit() -> Path:
    """Locate the kit repository even when apply.py is invoked from ~/.claude/skills/."""
    local_root = Path(__file__).resolve().parents[4]  # kitlib -> scripts -> claude-kit -> skills -> kit
    if (local_root / "base").is_dir() and (local_root / "profiles").is_dir():
        return local_root

    env_kit = os.environ.get("CLAUDE_KIT_PATH")
    if env_kit:
        cand = Path(env_kit).expanduser()
        if (cand / "base").is_dir():
            return cand

    cfg_file = Path.home() / ".claude" / KIT_CONFIG_NAME
    if cfg_file.is_file():
        try:
            kit_path = json.loads(cfg_file.read_text(encoding="utf-8")).get("kit_path", "")
            if kit_path:
                cand = Path(kit_path).expanduser()
                if (cand / "base").is_dir():
                    return cand
        except (OSError, json.JSONDecodeError):
            pass

    raise SystemExit("Kit directory not found. Run 'python install.py' from the claude-kit repository.")


