def read_kit_version(kit: Path) -> str:
    vf = kit / "VERSION"
    return vf.read_text(encoding="utf-8").strip() if vf.is_file() else "0.0.0"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_norm(data: bytes) -> str:
    """Hash with CRLF normalised to LF, so a checkout with autocrlf does not look modified."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def read_text_lossy(path: Path) -> str:
    """Read a text file for comparison only: undecodable bytes never crash (never rewrite from this)."""
    return path.read_text(encoding="utf-8", errors="replace")


def detect_eol(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def read_json(path: Path, kind: str, *, expect: type | None = dict):
    """Read a JSON file (BOM tolerated). Any problem aborts with a clear message; nothing is written."""
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{kind} ({path}) is not valid JSON ({exc}): leaving it untouched. Fix it and re-run.")
    except (OSError, UnicodeDecodeError) as exc:
        raise SystemExit(f"{kind} ({path}) cannot be read ({exc}): leaving it untouched.")
    if expect is not None and not isinstance(data, expect):
        want = {dict: "object", list: "array"}.get(expect, expect.__name__)
        raise SystemExit(f"{kind} ({path}) must contain a JSON {want}: leaving it untouched.")
    return data


def append_lines(path: Path, header: str, lines: list, dry: bool) -> None:
    """Append a block to a text file, preserving its EOL style and never rewriting existing lines."""
    existing = path.read_bytes().decode("utf-8", errors="surrogateescape") if path.exists() else ""
    eol = detect_eol(existing)
    block = eol.join([header, *lines]) + eol
    if existing:
        sep = "" if existing.endswith("\n") else eol
        block = sep + eol + block
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "ab") as fh:
            fh.write(block.encode("utf-8", errors="surrogateescape"))


def backup_file(path: Path, dry: bool) -> None:
    """Copy an existing file to <name>.bak (overwriting a previous backup)."""
    if not dry and path.is_file():
        shutil.copyfile(path, path.with_name(path.name + ".bak"))


def _specific_runner_rule(first: str, rest: list) -> bool:
    """True for a runner/docker rule that names a specific, safe literal tool or subcommand."""
    def literal(tok: str) -> str | None:
        name = tok.rstrip("*")
        return name if name and re.fullmatch(r"[a-z0-9][a-z0-9._@/-]*", name) and "*" not in name else None

    if not rest:
        return False
    if first == "docker":
        sub = literal(rest[0])
        if sub in DOCKER_SAFE_SUBCOMMANDS:
            return True
        pair = (rest[0], literal(rest[1]) if len(rest) > 1 else None)
        return pair in DOCKER_SAFE_PAIRS
    tool = literal(rest[0])
    return tool is not None and tool not in UNSAFE_BASH_COMMANDS


def runner_variants(rule: str, runners) -> list:
    """Concrete forms of a rule containing the {run} placeholder: one per runner, plus the bare tool."""
    if "{run}" not in rule:
        return [rule]
    forms = [rule.replace("{run}", r) for r in sorted(r for r in runners if r)]
    forms.append(re.sub(r"\{run\}\s*", "", rule))
    return forms


def unsafe_permission(rule: str, runners=()) -> str | None:
    """Return a reason if a profile/org permission rule is too broad, else None.

    A rule using {run} is checked once per possible runner (see runner_variants).
    """
    if "{run}" in rule:
        for form in runner_variants(rule, runners):
            reason = unsafe_permission(form)
            if reason:
                return reason
        return None
    if rule in DISALLOWED_PERMISSIONS:
        return f"unsafe permission '{rule}' is forbidden"
    m = re.fullmatch(r"Bash\((.*)\)", rule)
    if m:
        body = m.group(1).strip()
        tokens = body.split()
        first = body.split(" ", 1)[0].split(":", 1)[0].lower().rstrip("*")
        if first.endswith(".exe"):
            first = first[:-4]
        if first in RUNNER_COMMANDS or first == "docker":
            if _specific_runner_rule(first, [t.lower() for t in tokens[1:]]):
                return None
        if body.startswith("*"):
            return f"permission '{rule}' starts with a wildcard"
        if first in UNSAFE_BASH_COMMANDS:
            return f"permission '{rule}' allows arbitrary code execution or destructive commands ('{first}')"
    return None


def resolve_kit() -> Path:
    """Locate the kit repository even when apply.py is invoked from ~/.claude/skills/."""
    local_root = Path(__file__).resolve().parents[4]  # kitlib -> scripts -> claude-kit -> skills -> kit
    if (local_root / "base").is_dir() and (local_root / "profiles").is_dir():
        return local_root

    env_kit = os.environ.get("CLAUDE_KIT_PATH")
    if env_kit:
        cand = Path(env_kit).expanduser()
        if (cand / "base").is_dir():
            return cand

    cfg_file = Path.home() / ".claude" / KIT_CONFIG_NAME
    if cfg_file.is_file():
        try:
            kit_path = json.loads(cfg_file.read_text(encoding="utf-8-sig")).get("kit_path", "")
            if kit_path:
                cand = Path(kit_path).expanduser()
                if (cand / "base").is_dir():
                    return cand
        except (OSError, json.JSONDecodeError):
            pass

    raise SystemExit("Kit directory not found. Run 'python install.py' from the claude-kit repository.")


