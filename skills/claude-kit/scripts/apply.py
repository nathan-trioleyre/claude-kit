#!/usr/bin/env python3
"""apply.py: the MECHANICAL part of /claude-kit (what must stay deterministic).

Subcommands:
  list      lists known stack profiles in the kit, along with their age
  detect    detects which known profiles match a project
  apply     generates/merges Claude config into a project (first setup or full re-run)
  sync      re-applies only the kit-managed parts (settings, hooks, kit.json, org extras)
            to an already configured project, using the profiles recorded in kit.json
  doctor    reports drift between a project and the current kit (exit 1 if issues)
  validate  validates profile.json schema and practices.md constraints

Layers (later layers add to earlier ones, never remove): base -> org -> stack profiles -> project.

Safety rules:
  - an existing CLAUDE.md or .claude/rules/<stack>.md is never overwritten (.proposed)
  - existing settings.json: additive merge (legacy kit hooks upgraded safely)
  - a hook file is upgraded only if it is unmodified since the kit installed it
  - --dry-run writes nothing

No external dependencies: Python 3.9+ is sufficient.
"""
import argparse
import difflib
import fnmatch
import hashlib
import json
import os
import re
import shutil
import sys
from datetime import date
from pathlib import Path

STALE_DAYS = 90
MAX_DETECT_DEPTH = 5
MAX_PRACTICES_LINES = 15
IGNORED_DIRS = {
    "node_modules", ".git", ".venv", "venv", "bin", "obj",
    "dist", "__pycache__", ".claude", "target", ".next",
}
KIT_CONFIG_NAME = "claude-kit.json"
GENERATED_FOOTER_PREFIXES = ("<!-- Generated by claude-kit",)
DISALLOWED_PERMISSIONS = {"Bash(*)", "Bash(* *)", "Bash(rm *)", "Bash(sudo *)", "Write(*)", "Edit(*)"}
# Commands that can run arbitrary code or destroy data: never allowed with a wildcard in a profile.
UNSAFE_BASH_COMMANDS = {
    "bash", "sh", "zsh", "dash", "ksh", "pwsh", "powershell", "cmd", "eval", "exec", "env", "xargs",
    "python", "python3", "py", "node", "deno", "bun", "ruby", "perl", "php", "lua",
    "curl", "wget", "ssh", "scp", "nc", "ncat", "rm", "rmdir", "del", "sudo", "su", "doas",
    "chmod", "chown", "dd", "mkfs", "find", "npx", "pnpx", "bunx", "uvx", "pipx", "docker", "kubectl",
}
HOOK_VERSION_MARKER = "claude-kit-hook-version:"

COMMAND_LABELS = {
    "install": "Install",
    "dev": "Run dev",
    "test": "Test",
    "lint": "Lint",
    "format": "Format",
    "build": "Build",
    "verify": "Verify (before concluding a task)",
}
PLACEHOLDER = "_To be completed._"


def read_kit_version(kit: Path) -> str:
    vf = kit / "VERSION"
    return vf.read_text(encoding="utf-8").strip() if vf.is_file() else "0.0.0"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def unsafe_permission(rule: str) -> str | None:
    """Return a reason if a profile/org permission rule is too broad, else None."""
    if rule in DISALLOWED_PERMISSIONS:
        return f"unsafe permission '{rule}' is forbidden"
    m = re.fullmatch(r"Bash\((.*)\)", rule)
    if m:
        body = m.group(1).strip()
        first = body.split(" ", 1)[0].split(":", 1)[0].lower()
        if first.endswith(".exe"):
            first = first[:-4]
        if first.startswith("*"):
            return f"permission '{rule}' starts with a wildcard"
        if first in UNSAFE_BASH_COMMANDS:
            return f"permission '{rule}' allows arbitrary code execution or destructive commands ('{first}')"
    return None


def resolve_kit() -> Path:
    """Locate the kit repository even when apply.py is invoked from ~/.claude/skills/."""
    local_root = Path(__file__).resolve().parents[3]
    if (local_root / "base").is_dir() and (local_root / "profiles").is_dir():
        return local_root

    env_kit = os.environ.get("CLAUDE_KIT_PATH")
    if env_kit:
        cand = Path(env_kit).expanduser()
        if (cand / "base").is_dir():
            return cand

    cfg_file = Path.home() / ".claude" / KIT_CONFIG_NAME
    if cfg_file.is_file():
        try:
            kit_path = json.loads(cfg_file.read_text(encoding="utf-8")).get("kit_path", "")
            if kit_path:
                cand = Path(kit_path).expanduser()
                if (cand / "base").is_dir():
                    return cand
        except (OSError, json.JSONDecodeError):
            pass

    raise SystemExit("Kit directory not found. Run 'python install.py' from the claude-kit repository.")


KIT = resolve_kit()
BASE = KIT / "base"
PROFILES = KIT / "profiles"
ORG = KIT / "org"
KIT_VERSION = read_kit_version(KIT)


# -------------------------------------------------------------------- profiles
def profile_dirs() -> list:
    if not PROFILES.is_dir():
        return []
    return sorted(
        p for p in PROFILES.iterdir()
        if p.is_dir() and not p.name.startswith("_") and (p / "profile.json").is_file()
    )


def load_profile(name: str) -> dict:
    folder = PROFILES / name
    file = folder / "profile.json"
    if not file.is_file():
        raise SystemExit(f"Profile not found: {name} (expected: {file})")
    data = json.loads(file.read_text(encoding="utf-8"))
    missing = [k for k in ("stack", "commands", "last_verified") if k not in data]
    if missing:
        raise SystemExit(f"Invalid profile {name}, missing keys: {', '.join(missing)}")
    practices = folder / "practices.md"
    data["_practices"] = practices.read_text(encoding="utf-8").strip() if practices.is_file() else ""
    return data


def age_days(profile: dict) -> int:
    try:
        return (date.today() - date.fromisoformat(profile["last_verified"])).days
    except ValueError:
        return 10**6  # unreadable date: treated as stale


def cmd_list(_args) -> None:
    out = []
    for folder in profile_dirs():
        p = load_profile(folder.name)
        age = age_days(p)
        out.append({
            "stack": p["stack"],
            "display_name": p.get("display_name", p["stack"]),
            "last_verified": p["last_verified"],
            "age_days": age,
            "stale": age > STALE_DAYS,
        })
    print(json.dumps(out, ensure_ascii=False, indent=2))


# ------------------------------------------------------------------- validate
def validate_profile_folder(folder: Path) -> list:
    """Validate profile.json and practices.md for one stack folder; return error strings."""
    errors = []
    pjson = folder / "profile.json"
    if not pjson.is_file():
        return [f"{folder.name}: missing profile.json"]
    try:
        data = json.loads(pjson.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"{folder.name}: invalid JSON in profile.json ({exc})"]
    if not isinstance(data, dict):
        return [f"{folder.name}: profile.json must be a JSON object"]

    required = ("stack", "display_name", "detect", "commands", "permissions_allow",
                "format_rules", "sources", "last_verified")
    for key in required:
        if key not in data:
            errors.append(f"{folder.name}: missing key '{key}'")

    stack = data.get("stack")
    if isinstance(stack, str):
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", stack):
            errors.append(f"{folder.name}: stack '{stack}' must be lowercase alphanumeric/hyphens")
        if stack != folder.name:
            errors.append(f"{folder.name}: stack '{stack}' does not match folder name")

    detect = data.get("detect")
    if detect is not None and (not isinstance(detect, list) or not detect or not all(isinstance(x, str) and x for x in detect)):
        errors.append(f"{folder.name}: 'detect' must be a non-empty list of patterns")

    commands = data.get("commands")
    if commands is not None:
        if not isinstance(commands, dict) or "verify" not in commands:
            errors.append(f"{folder.name}: 'commands' must be an object containing 'verify'")
        elif any(v is not None and not isinstance(v, str) for v in commands.values()):
            errors.append(f"{folder.name}: command values must be strings or null")

    perms = data.get("permissions_allow")
    if perms is not None:
        if not isinstance(perms, list) or not all(isinstance(r, str) for r in perms):
            errors.append(f"{folder.name}: 'permissions_allow' must be a list of strings")
        else:
            for rule in perms:
                reason = unsafe_permission(rule)
                if reason:
                    errors.append(f"{folder.name}: {reason}")

    fmt_rules = data.get("format_rules")
    if fmt_rules is not None:
        if not isinstance(fmt_rules, list):
            errors.append(f"{folder.name}: 'format_rules' must be a list")
        else:
            for idx, rule in enumerate(fmt_rules):
                if not isinstance(rule, dict):
                    errors.append(f"{folder.name}: format_rules[{idx}] must be an object")
                    continue
                exts = rule.get("extensions")
                cmd = rule.get("command")
                if not isinstance(exts, list) or not exts or not all(isinstance(e, str) and e.startswith(".") for e in exts):
                    errors.append(f"{folder.name}: format_rules[{idx}].extensions must list '.ext' strings")
                if not isinstance(cmd, list) or not cmd or "{file}" not in cmd:
                    errors.append(f"{folder.name}: format_rules[{idx}].command must include '{{file}}'")

    sources = data.get("sources")
    if sources is not None:
        if not isinstance(sources, list) or not sources or not all(isinstance(s, str) and s.startswith(("http://", "https://")) for s in sources):
            errors.append(f"{folder.name}: 'sources' must be a non-empty list of URLs")

    last_verified = data.get("last_verified")
    if isinstance(last_verified, str):
        try:
            date.fromisoformat(last_verified)
        except ValueError:
            errors.append(f"{folder.name}: invalid ISO date '{last_verified}' in last_verified")

    paths = data.get("paths")
    if paths is not None and (not isinstance(paths, list) or not all(isinstance(x, str) and x for x in paths)):
        errors.append(f"{folder.name}: optional 'paths' must be a list of non-empty glob strings")

    practices_file = folder / "practices.md"
    if not practices_file.is_file():
        errors.append(f"{folder.name}: missing practices.md")
    else:
        non_empty_lines = [line for line in practices_file.read_text(encoding="utf-8").splitlines() if line.strip()]
        if not non_empty_lines:
            errors.append(f"{folder.name}: practices.md is empty")
        elif len(non_empty_lines) > MAX_PRACTICES_LINES:
            errors.append(f"{folder.name}: practices.md has {len(non_empty_lines)} lines (max {MAX_PRACTICES_LINES})")

    return errors


def cmd_validate(args) -> None:
    if args.profiles:
        folders = [PROFILES / name for name in args.profiles]
    else:
        folders = [p for p in sorted(PROFILES.iterdir()) if p.is_dir() and not p.name.startswith("_")] if PROFILES.is_dir() else []

    if not folders:
        print("No profiles to validate.")
        return

    all_errors = []
    for folder in folders:
        if not folder.is_dir():
            all_errors.append(f"{folder.name}: profile directory not found")
        else:
            all_errors.extend(validate_profile_folder(folder))

    if all_errors:
        for err in all_errors:
            print(f"ERROR: {err}", file=sys.stderr)
        raise SystemExit(1)

    print(f"OK: validated {len(folders)} profile(s).")


# ------------------------------------------------------------------- detection
def collect_project_files(project: Path, max_depth: int = MAX_DETECT_DEPTH) -> list:
    """Single top-down walk pruning IGNORED_DIRS up to max_depth."""
    rel_files = []
    for root, dirs, files in os.walk(project, topdown=True):
        rel_root = Path(root).relative_to(project)
        depth = 0 if rel_root == Path(".") else len(rel_root.parts)
        if depth >= max_depth:
            dirs[:] = []
        else:
            dirs[:] = sorted(d for d in dirs if d not in IGNORED_DIRS)

        prefix = "" if rel_root == Path(".") else rel_root.as_posix() + "/"
        for fname in files:
            rel_files.append(prefix + fname)
    return rel_files


def pattern_matches(rel_files: list, pattern: str) -> bool:
    if "/" in pattern:
        return any(fnmatch.fnmatch(rp, pattern) for rp in rel_files)
    return any(fnmatch.fnmatch(rp.rsplit("/", 1)[-1], pattern) for rp in rel_files)


def detect_matched(project: Path) -> list:
    rel_files = collect_project_files(project)
    return [p["stack"] for p in (load_profile(f.name) for f in profile_dirs())
            if any(pattern_matches(rel_files, pat) for pat in p.get("detect", []))]


def cmd_detect(args) -> None:
    project = Path(args.project).resolve()
    known = [load_profile(f.name)["stack"] for f in profile_dirs()]
    print(json.dumps({"matched": detect_matched(project), "known_profiles": known}, ensure_ascii=False))


# ----------------------------------------------------------------------- apply
def _kit_hook_tag(command: str) -> str | None:
    if ".claude/hooks/" not in command:
        return None
    for script in ("guard.py", "format.py"):
        if script in command:
            return script
    return None


def merge_settings(existing: dict, wanted: dict):
    result = json.loads(json.dumps(existing))
    changes = []
    perms = result.setdefault("permissions", {})
    for key in ("allow", "deny"):
        current = perms.setdefault(key, [])
        for rule in wanted.get("permissions", {}).get(key, []):
            if rule not in current:
                current.append(rule)
                changes.append(f"permissions.{key}: {rule}")

    hooks = result.setdefault("hooks", {})
    for event, groups in wanted.get("hooks", {}).items():
        current_groups = hooks.setdefault(event, [])
        for wanted_group in groups:
            wanted_matcher = wanted_group.get("matcher")
            for wanted_hook in wanted_group.get("hooks", []):
                wanted_cmd = wanted_hook["command"]
                wanted_tag = _kit_hook_tag(wanted_cmd)

                exact_group = next(
                    (g for g in current_groups if any(h.get("command") == wanted_cmd for h in g.get("hooks", []))),
                    None,
                )
                if exact_group is not None:
                    if wanted_matcher and exact_group.get("matcher") != wanted_matcher:
                        exact_group["matcher"] = wanted_matcher
                        changes.append(f"hooks.{event} matcher -> {wanted_matcher}")
                    continue

                if wanted_tag:
                    upgraded = False
                    for g in list(current_groups):
                        group_hooks = g.get("hooks", [])
                        kept = [h for h in group_hooks if _kit_hook_tag(h.get("command", "")) != wanted_tag]
                        if len(kept) != len(group_hooks):
                            upgraded = True
                            if kept:
                                g["hooks"] = kept
                            else:
                                current_groups.remove(g)
                    if upgraded:
                        current_groups.append({**wanted_group, "hooks": [wanted_hook]})
                        changes.append(f"upgraded hooks.{event}: {wanted_cmd}")
                        continue

                current_groups.append({**wanted_group, "hooks": [wanted_hook]})
                changes.append(f"hooks.{event}: {wanted_cmd}")

    return result, changes


def load_org_settings() -> dict:
    f = ORG / "settings.json"
    if not f.is_file():
        return {}
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise SystemExit(f"{f} is not valid JSON.")


def build_wanted_settings(profiles: list, use_org: bool = True) -> dict:
    """Layer settings: base -> org -> stack profiles (always additive)."""
    wanted = json.loads((BASE / "settings.base.json").read_text(encoding="utf-8"))
    allow = wanted["permissions"]["allow"]
    deny = wanted["permissions"]["deny"]
    if use_org:
        org = load_org_settings()
        for key, target in (("allow", allow), ("deny", deny)):
            for rule in org.get("permissions", {}).get(key, []):
                if rule not in target:
                    target.append(rule)
        for event, groups in org.get("hooks", {}).items():
            wanted["hooks"].setdefault(event, []).extend(groups)
    for p in profiles:
        for rule in p.get("permissions_allow", []):
            if rule not in allow:
                allow.append(rule)
    return wanted


def read_org_text(name: str) -> str:
    f = ORG / name
    return f.read_text(encoding="utf-8").strip() if f.is_file() else ""


def render_commands(profiles: list, overrides: dict) -> str:
    lines = []
    multi = len(profiles) > 1
    for p in profiles:
        commands = {**p["commands"], **overrides.get(p["stack"], {})}
        for key, label in COMMAND_LABELS.items():
            cmd = commands.get(key)
            if cmd:
                prefix = f"[{p.get('display_name', p['stack'])}] " if multi else ""
                lines.append(f"- {prefix}{label}: `{cmd}`")
    return "\n".join(lines) or PLACEHOLDER


def resolve_rule_paths(profile: dict, ctx: dict) -> list:
    rule_paths_map = ctx.get("rule_paths", {})
    if profile["stack"] in rule_paths_map:
        return rule_paths_map[profile["stack"]] or []
    return profile.get("paths") or []


def render_practices(profiles: list, ctx: dict) -> str:
    if len(profiles) == 1:
        p = profiles[0]
        if resolve_rule_paths(p, ctx) and p["_practices"]:
            return f"See `.claude/rules/{p['stack']}.md`."
        return p["_practices"] or PLACEHOLDER

    blocks = []
    for p in profiles:
        if not p["_practices"]:
            continue
        name = p.get("display_name", p["stack"])
        if resolve_rule_paths(p, ctx):
            blocks.append(f"### {name}\nSee `.claude/rules/{p['stack']}.md`.")
        else:
            blocks.append(f"### {name}\n{p['_practices']}")
    return "\n\n".join(blocks) or PLACEHOLDER


def render_rule_file(profile: dict, paths: list) -> str:
    path_lines = "\n".join(f'  - "{pat}"' for pat in paths)
    title = profile.get("display_name", profile["stack"])
    return f"---\npaths:\n{path_lines}\n---\n\n# {title} Conventions\n\n{profile['_practices']}\n"


def write_text(path: Path, content: str, dry: bool) -> None:
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def write_non_destructive(target: Path, rel_label: str, rendered: str, dry: bool, report: list,
                          ignore_prefixes: tuple = (), state: dict | None = None) -> None:
    """Create target if missing; if it differs, write <target>.proposed and show diff in dry-run.

    `state` (kit.json "rendered") remembers the hash of what the kit last generated for this file.
    When the kit output is unchanged since then, a user-edited file is left alone silently
    instead of producing a new .proposed file at every re-run.
    """
    def normalize(text: str) -> str:
        if not ignore_prefixes:
            return text
        return "\n".join(l for l in text.splitlines() if not l.startswith(ignore_prefixes))

    rendered_hash = sha256_text(normalize(rendered))

    if not target.exists():
        write_text(target, rendered, dry)
        report.append(f"created   {rel_label}")
        if state is not None:
            state[rel_label] = rendered_hash
        return

    existing = target.read_text(encoding="utf-8")

    if normalize(existing) == normalize(rendered):
        report.append(f"unchanged {rel_label} (already matches what the kit generates)")
        if state is not None:
            state[rel_label] = rendered_hash
        return

    if state is not None and state.get(rel_label) == rendered_hash:
        report.append(f"unchanged {rel_label} (customized by you; kit output has not changed since last run)")
        return
    if state is not None:
        state[rel_label] = rendered_hash

    proposed = target.with_name(target.name + ".proposed")
    proposed_label = rel_label + ".proposed"
    write_text(proposed, rendered, dry)
    report.append(f"proposed  {rel_label} already exists -> written to {proposed_label} (compare manually)")
    if dry:
        diff = list(difflib.unified_diff(
            existing.splitlines(), rendered.splitlines(),
            fromfile=rel_label, tofile=proposed_label, lineterm="",
        ))
        report.extend(f"          {line}" for line in diff)


def load_context(context_arg: str | None) -> dict:
    if not context_arg:
        return {}
    raw = sys.stdin.read() if context_arg == "-" else Path(context_arg).read_text(encoding="utf-8")
    return json.loads(raw) if raw.strip() else {}


def load_kit_json(project: Path) -> dict:
    f = project / ".claude" / "kit.json"
    if not f.is_file():
        return {}
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except json.JSONDecodeError:
        return {}


def hook_version(text: str) -> int:
    m = re.search(re.escape(HOOK_VERSION_MARKER) + r"\s*(\d+)", text)
    return int(m.group(1)) if m else 0


# ---------------------------------------------------------- managed file sync
def sync_file(src: Path, dest: Path, label: str, managed: dict, dry: bool, report: list, force: bool) -> None:
    """Copy a kit file into the project.

    - missing: created
    - identical: unchanged
    - differs but unmodified since the kit installed it (hash recorded in kit.json): upgraded
    - differs and modified by the user (or installed before hashes were recorded): skipped
      unless `force` (--force-hooks)
    """
    src_bytes = src.read_bytes()
    src_hash = sha256_bytes(src_bytes)

    def put(verb: str) -> None:
        if not dry:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
            if src.suffix == ".sh":
                dest.chmod(dest.stat().st_mode | 0o111)
        managed[label] = src_hash
        report.append(f"{verb} {label}")

    if not dest.exists():
        put("created  ")
        return
    dest_hash = sha256_bytes(dest.read_bytes())
    if dest_hash == src_hash:
        managed[label] = src_hash
        report.append(f"unchanged {label}")
    elif force or managed.get(label) == dest_hash:
        put("upgraded " if not force else "forced   ")
    else:
        report.append(f"skipped   {label} differs from the kit and was modified locally (use --force-hooks to overwrite)")


def sync_extras(project: Path, managed: dict, dry: bool, report: list, force: bool, use_org: bool) -> None:
    """Hooks, then optional agents/commands from base/ and org/ (non-destructive)."""
    for src in sorted((BASE / "hooks").iterdir()):
        if src.is_file() and not src.name.startswith("."):
            sync_file(src, project / ".claude" / "hooks" / src.name, f".claude/hooks/{src.name}",
                      managed, dry, report, force)

    roots = [BASE] + ([ORG] if use_org else [])
    for root in roots:
        for sub in ("agents", "commands"):
            folder = root / sub
            if not folder.is_dir():
                continue
            for src in sorted(folder.glob("*.md")):
                sync_file(src, project / ".claude" / sub / src.name, f".claude/{sub}/{src.name}",
                          managed, dry, report, False)

    mcp_src = ORG / "mcp.json" if use_org else None
    if mcp_src and mcp_src.is_file():
        wanted = json.loads(mcp_src.read_text(encoding="utf-8")).get("mcpServers", {})
        target = project / ".mcp.json"
        existing = {}
        if target.exists():
            try:
                existing = json.loads(target.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                report.append("skipped   .mcp.json is not valid JSON (left untouched)")
                return
        servers = existing.setdefault("mcpServers", {})
        added = [name for name in wanted if name not in servers]
        for name in added:
            servers[name] = wanted[name]
        if added:
            write_text(target, json.dumps(existing, indent=2, ensure_ascii=False) + "\n", dry)
            report.append(f"merged    .mcp.json (+{', '.join(added)})")
        else:
            report.append("unchanged .mcp.json")


def apply_settings(project: Path, profiles: list, dry: bool, report: list, use_org: bool) -> None:
    settings_path = project / ".claude" / "settings.json"
    wanted = build_wanted_settings(profiles, use_org)
    if settings_path.exists():
        try:
            existing = json.loads(settings_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            raise SystemExit(f"{settings_path} is not valid JSON: leaving it untouched. Fix it and re-run.")
        merged, changes = merge_settings(existing, wanted)
        if changes:
            write_text(settings_path, json.dumps(merged, indent=2, ensure_ascii=False) + "\n", dry)
            report.append(f"merged    .claude/settings.json (+{len(changes)} updates)")
            report.extend(f"           + {c}" for c in changes)
        else:
            report.append("unchanged .claude/settings.json (already up to date)")
    else:
        write_text(settings_path, json.dumps(wanted, indent=2, ensure_ascii=False) + "\n", dry)
        report.append("created   .claude/settings.json")


def update_gitignore(project: Path, dry: bool, report: list) -> None:
    gitignore = project / ".gitignore"
    wanted_lines = [".claude/settings.local.json", ".claude/logs/", "CLAUDE.local.md",
                    "CLAUDE.md.proposed", ".claude/rules/*.proposed"]
    current = gitignore.read_text(encoding="utf-8").splitlines() if gitignore.exists() else []
    current_set = {line.strip() for line in current}
    missing = [line for line in wanted_lines if line not in current_set]
    if missing:
        text = (gitignore.read_text(encoding="utf-8").rstrip("\n") + "\n\n" if current else "")
        write_text(gitignore, text + "# Claude Code (local files)\n" + "\n".join(missing) + "\n", dry)
        report.append(f"updated   .gitignore (+{len(missing)} lines)")


def write_kit_json(project: Path, profiles: list, previous: dict, managed: dict, rendered: dict,
                   dry: bool, report: list) -> None:
    known = dict(previous.get("profiles", {}))
    for p in profiles:
        known[p["stack"]] = {"last_verified": p["last_verified"]}
    format_rules = []
    for name in list(known):
        try:
            format_rules.extend(load_profile(name).get("format_rules", []))
        except SystemExit:
            pass  # profile deleted from kit in the meantime
    kit_json = {
        "generated_by": "claude-kit",
        "kit_version": KIT_VERSION,
        "date": date.today().isoformat(),
        "profiles": known,
        "format_rules": format_rules,
        "managed": managed,
        "rendered": rendered,
    }
    write_text(project / ".claude" / "kit.json", json.dumps(kit_json, indent=2, ensure_ascii=False) + "\n", dry)
    report.append("written   .claude/kit.json")


# ------------------------------------------------------------------ run modes
def run(project: Path, profile_names: list, ctx: dict, dry: bool, *, full: bool,
        force_hooks: bool = False, use_org: bool = True) -> list:
    report = []
    previous = load_kit_json(project)
    managed = dict(previous.get("managed", {}))
    rendered_state = dict(previous.get("rendered", {}))

    profiles = [load_profile(name) for name in profile_names]
    for p in profiles:
        if age_days(p) > STALE_DAYS:
            report.append(f"! profile '{p['stack']}' is stale or unverified ({age_days(p)}d): consider /claude-kit-refresh {p['stack']}")

    if full:
        # 1. CLAUDE.md (never overwritten)
        template = (BASE / "CLAUDE.md.template").read_text(encoding="utf-8")
        org_rules = read_org_text("rules.md") if use_org else ""
        values = {
            "PROJECT_NAME": ctx.get("name") or project.name,
            "DESCRIPTION": ctx.get("description") or PLACEHOLDER,
            "STACK": "\n".join(f"- {p.get('display_name', p['stack'])}" for p in profiles) or PLACEHOLDER,
            "COMMANDS": render_commands(profiles, ctx.get("commands_override", {})),
            "ARCHITECTURE": ctx.get("architecture") or PLACEHOLDER,
            "PRACTICES": render_practices(profiles, ctx),
            "GOTCHAS": ctx.get("gotchas") or PLACEHOLDER,
            "ORG_RULES": ("\n" + org_rules) if org_rules else "",
            "DATE": date.today().isoformat(),
            "PROFILES": ", ".join(p["stack"] for p in profiles) or "none",
        }
        rendered = template
        for key, value in values.items():
            rendered = rendered.replace("{{" + key + "}}", value)
        write_non_destructive(project / "CLAUDE.md", "CLAUDE.md", rendered, dry, report,
                              GENERATED_FOOTER_PREFIXES, rendered_state)

        # 2. Modular .claude/rules/<stack>.md (optional, never overwritten)
        for p in profiles:
            rule_paths = resolve_rule_paths(p, ctx)
            if rule_paths and p["_practices"]:
                label = f".claude/rules/{p['stack']}.md"
                write_non_destructive(project / label, label, render_rule_file(p, rule_paths),
                                      dry, report, state=rendered_state)

    # 3. settings.json (additive merge + legacy kit hook upgrade)
    apply_settings(project, profiles, dry, report, use_org)

    # 4. hooks, agents, commands, MCP servers
    sync_extras(project, managed, dry, report, force_hooks, use_org)

    # 5. kit.json (metadata, formatting rules, hashes)
    write_kit_json(project, profiles, previous, managed, rendered_state, dry, report)

    # 6. .gitignore (local Claude files)
    update_gitignore(project, dry, report)
    return report


def emit(report: list, dry: bool) -> None:
    print(("[DRY-RUN: nothing was written]\n" if dry else "") + "\n".join(report))


def cmd_apply(args) -> None:
    project = Path(args.project).resolve()
    ctx = load_context(args.context)
    emit(run(project, args.profiles, ctx, args.dry_run, full=True,
             force_hooks=args.force_hooks, use_org=not args.no_org), args.dry_run)


def cmd_sync(args) -> None:
    project = Path(args.project).resolve()
    previous = load_kit_json(project)
    if not previous:
        raise SystemExit("No .claude/kit.json: this project was never configured. Run /claude-kit (apply) first.")
    names = args.profiles or [n for n in previous.get("profiles", {}) if (PROFILES / n / "profile.json").is_file()]
    emit(run(project, names, {}, args.dry_run, full=False,
             force_hooks=args.force_hooks, use_org=not args.no_org), args.dry_run)


def cmd_doctor(args) -> None:
    project = Path(args.project).resolve()
    kit_json = load_kit_json(project)
    issues, oks = [], []
    if not kit_json:
        print("ISSUE: no .claude/kit.json: project not configured. Run /claude-kit.")
        raise SystemExit(1)

    if kit_json.get("kit_version") != KIT_VERSION:
        issues.append(f"project configured with kit {kit_json.get('kit_version', '?')}, current kit is {KIT_VERSION}: run sync")
    else:
        oks.append(f"kit version {KIT_VERSION}")

    managed = kit_json.get("managed", {})
    for src in sorted((BASE / "hooks").iterdir()):
        if not src.is_file() or src.name.startswith("."):
            continue
        label = f".claude/hooks/{src.name}"
        dest = project / label
        if not dest.is_file():
            issues.append(f"{label} is missing")
            continue
        src_text, dest_bytes = src.read_text(encoding="utf-8"), dest.read_bytes()
        if sha256_bytes(dest_bytes) == sha256_bytes(src.read_bytes()):
            oks.append(f"{label} up to date (v{hook_version(src_text)})")
        elif managed.get(label) == sha256_bytes(dest_bytes):
            issues.append(f"{label} outdated (v{hook_version(dest_bytes.decode('utf-8', 'ignore'))} < v{hook_version(src_text)}): run sync")
        else:
            issues.append(f"{label} modified locally or predates hash tracking: run sync --force-hooks to reset")

    settings_path = project / ".claude" / "settings.json"
    if settings_path.is_file():
        try:
            profile_names = [n for n in kit_json.get("profiles", {}) if (PROFILES / n / "profile.json").is_file()]
            _, changes = merge_settings(json.loads(settings_path.read_text(encoding="utf-8")),
                                        build_wanted_settings([load_profile(n) for n in profile_names], not args.no_org))
            if changes:
                issues.append(f".claude/settings.json is missing {len(changes)} kit entries: run sync")
            else:
                oks.append("settings.json has every kit permission and hook")
        except json.JSONDecodeError:
            issues.append(".claude/settings.json is not valid JSON")
    else:
        issues.append(".claude/settings.json is missing")

    for name, info in kit_json.get("profiles", {}).items():
        if not (PROFILES / name / "profile.json").is_file():
            issues.append(f"profile '{name}' no longer exists in the kit")
            continue
        p = load_profile(name)
        if age_days(p) > STALE_DAYS:
            issues.append(f"profile '{name}' is stale/unverified ({age_days(p)}d): /claude-kit-refresh {name}")
        if p["last_verified"] != info.get("last_verified"):
            issues.append(f"profile '{name}' was refreshed in the kit since this project was set up: re-run /claude-kit")

    detected = detect_matched(project)
    for name in detected:
        if name not in kit_json.get("profiles", {}):
            issues.append(f"stack '{name}' detected but not configured: re-run /claude-kit")

    claude_md = project / "CLAUDE.md"
    if claude_md.is_file():
        left = claude_md.read_text(encoding="utf-8").count(PLACEHOLDER)
        (issues if left else oks).append(f"CLAUDE.md has {left} section(s) still marked '{PLACEHOLDER}'" if left else "CLAUDE.md fully filled")
    else:
        issues.append("CLAUDE.md is missing")
    leftovers = [p.relative_to(project).as_posix() for p in project.rglob("*.proposed")
                 if not any(part in IGNORED_DIRS for part in p.relative_to(project).parts)]
    for rel in leftovers:
        issues.append(f"{rel} is waiting to be merged or deleted")

    print("\n".join([f"ok     {o}" for o in oks] + [f"ISSUE  {i}" for i in issues]))
    if issues:
        raise SystemExit(1)


# ------------------------------------------------------------------------ main
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("list", help="list kit profiles").set_defaults(func=cmd_list)

    p_detect = sub.add_parser("detect", help="detect known profiles in a project")
    p_detect.add_argument("--project", default=".")
    p_detect.set_defaults(func=cmd_detect)

    p_validate = sub.add_parser("validate", help="validate profile schemas and practices.md")
    p_validate.add_argument("--profiles", nargs="*", default=[], help="specific stacks to validate (default: all)")
    p_validate.set_defaults(func=cmd_validate)

    for name, func, help_text in (("apply", cmd_apply, "generate config in a project"),
                                  ("sync", cmd_sync, "refresh kit-managed files of a configured project")):
        sp = sub.add_parser(name, help=help_text)
        sp.add_argument("--project", default=".")
        sp.add_argument("--profiles", nargs="*", default=[], help="stack names (e.g., python angular)")
        sp.add_argument("--dry-run", action="store_true")
        sp.add_argument("--force-hooks", action="store_true", help="overwrite hooks even if modified locally")
        sp.add_argument("--no-org", action="store_true", help="ignore the optional org/ layer")
        if name == "apply":
            sp.add_argument("--context", help="JSON path or '-' for stdin: name, description, architecture, gotchas, commands_override, rule_paths")
        sp.set_defaults(func=func)

    p_doctor = sub.add_parser("doctor", help="report drift between a project and the kit")
    p_doctor.add_argument("--project", default=".")
    p_doctor.add_argument("--no-org", action="store_true")
    p_doctor.set_defaults(func=cmd_doctor)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
