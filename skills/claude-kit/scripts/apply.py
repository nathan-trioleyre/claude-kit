#!/usr/bin/env python3
"""apply.py: the MECHANICAL part of /claude-kit (what must stay deterministic).

Four subcommands:
  list      lists known stack profiles in the kit, along with their age
  detect    detects which known profiles match a project
  apply     generates/merges Claude config into a project
  validate  validates profile.json schema and practices.md constraints

Safety rules:
  - an existing CLAUDE.md or .claude/rules/<stack>.md is never overwritten (.proposed)
  - existing settings.json: additive merge (legacy kit hooks upgraded safely)
  - existing hooks that differ are never overwritten
  - --dry-run writes nothing

No external dependencies: Python 3.9+ is sufficient.
"""
import argparse
import difflib
import fnmatch
import json
import os
import re
import shutil
import sys
from datetime import date
from pathlib import Path

STALE_DAYS = 90
MAX_DETECT_DEPTH = 5
MAX_PRACTICES_LINES = 15
IGNORED_DIRS = {
    "node_modules", ".git", ".venv", "venv", "bin", "obj",
    "dist", "__pycache__", ".claude", "target", ".next",
}
KIT_CONFIG_NAMES = ("claude-kit.json", "claude-bootstrap.json")
GENERATED_FOOTER_PREFIXES = ("<!-- Generated by claude-kit", "<!-- Generated by claude-bootstrap")
DISALLOWED_PERMISSIONS = {"Bash(*)", "Bash(* *)", "Bash(rm *)", "Bash(sudo *)", "Write(*)", "Edit(*)"}

COMMAND_LABELS = {
    "install": "Install",
    "dev": "Run dev",
    "test": "Test",
    "lint": "Lint",
    "format": "Format",
    "build": "Build",
    "verify": "Verify (before concluding a task)",
}
PLACEHOLDER = "_To be completed._"


def resolve_kit() -> Path:
    """Locate the kit repository even when apply.py is invoked from ~/.claude/skills/."""
    local_root = Path(__file__).resolve().parents[3]
    if (local_root / "base").is_dir() and (local_root / "profiles").is_dir():
        return local_root

    env_kit = os.environ.get("CLAUDE_KIT_PATH")
    if env_kit:
        cand = Path(env_kit).expanduser()
        if (cand / "base").is_dir():
            return cand

    claude_dir = Path.home() / ".claude"
    for cfg_name in KIT_CONFIG_NAMES:
        cfg_file = claude_dir / cfg_name
        if cfg_file.is_file():
            try:
                kit_path = json.loads(cfg_file.read_text(encoding="utf-8")).get("kit_path", "")
                if kit_path:
                    cand = Path(kit_path).expanduser()
                    if (cand / "base").is_dir():
                        return cand
            except (OSError, json.JSONDecodeError):
                pass

    raise SystemExit("Kit directory not found. Run 'python install.py' from the claude-kit repository.")


KIT = resolve_kit()
BASE = KIT / "base"
PROFILES = KIT / "profiles"


# -------------------------------------------------------------------- profiles
def profile_dirs() -> list:
    if not PROFILES.is_dir():
        return []
    return sorted(
        p for p in PROFILES.iterdir()
        if p.is_dir() and not p.name.startswith("_") and (p / "profile.json").is_file()
    )


def load_profile(name: str) -> dict:
    folder = PROFILES / name
    file = folder / "profile.json"
    if not file.is_file():
        raise SystemExit(f"Profile not found: {name} (expected: {file})")
    data = json.loads(file.read_text(encoding="utf-8"))
    missing = [k for k in ("stack", "commands", "last_verified") if k not in data]
    if missing:
        raise SystemExit(f"Invalid profile {name}, missing keys: {', '.join(missing)}")
    practices = folder / "practices.md"
    data["_practices"] = practices.read_text(encoding="utf-8").strip() if practices.is_file() else ""
    return data


def age_days(profile: dict) -> int:
    try:
        return (date.today() - date.fromisoformat(profile["last_verified"])).days
    except ValueError:
        return 10**6  # unreadable date: treated as stale


def cmd_list(_args) -> None:
    out = []
    for folder in profile_dirs():
        p = load_profile(folder.name)
        age = age_days(p)
        out.append({
            "stack": p["stack"],
            "display_name": p.get("display_name", p["stack"]),
            "last_verified": p["last_verified"],
            "age_days": age,
            "stale": age > STALE_DAYS,
        })
    print(json.dumps(out, ensure_ascii=False, indent=2))


# ------------------------------------------------------------------- validate
def validate_profile_folder(folder: Path) -> list:
    """Validate profile.json and practices.md for one stack folder; return error strings."""
    errors = []
    pjson = folder / "profile.json"
    if not pjson.is_file():
        return [f"{folder.name}: missing profile.json"]
    try:
        data = json.loads(pjson.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"{folder.name}: invalid JSON in profile.json ({exc})"]
    if not isinstance(data, dict):
        return [f"{folder.name}: profile.json must be a JSON object"]

    required = ("stack", "display_name", "detect", "commands", "permissions_allow",
                "format_rules", "sources", "last_verified")
    for key in required:
        if key not in data:
            errors.append(f"{folder.name}: missing key '{key}'")

    stack = data.get("stack")
    if isinstance(stack, str):
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", stack):
            errors.append(f"{folder.name}: stack '{stack}' must be lowercase alphanumeric/hyphens")
        if stack != folder.name:
            errors.append(f"{folder.name}: stack '{stack}' does not match folder name")

    detect = data.get("detect")
    if detect is not None and (not isinstance(detect, list) or not detect or not all(isinstance(x, str) and x for x in detect)):
        errors.append(f"{folder.name}: 'detect' must be a non-empty list of patterns")

    commands = data.get("commands")
    if commands is not None:
        if not isinstance(commands, dict) or "verify" not in commands:
            errors.append(f"{folder.name}: 'commands' must be an object containing 'verify'")
        elif any(v is not None and not isinstance(v, str) for v in commands.values()):
            errors.append(f"{folder.name}: command values must be strings or null")

    perms = data.get("permissions_allow")
    if perms is not None:
        if not isinstance(perms, list) or not all(isinstance(r, str) for r in perms):
            errors.append(f"{folder.name}: 'permissions_allow' must be a list of strings")
        else:
            for rule in perms:
                if rule in DISALLOWED_PERMISSIONS:
                    errors.append(f"{folder.name}: unsafe permission '{rule}' is forbidden")

    fmt_rules = data.get("format_rules")
    if fmt_rules is not None:
        if not isinstance(fmt_rules, list):
            errors.append(f"{folder.name}: 'format_rules' must be a list")
        else:
            for idx, rule in enumerate(fmt_rules):
                if not isinstance(rule, dict):
                    errors.append(f"{folder.name}: format_rules[{idx}] must be an object")
                    continue
                exts = rule.get("extensions")
                cmd = rule.get("command")
                if not isinstance(exts, list) or not exts or not all(isinstance(e, str) and e.startswith(".") for e in exts):
                    errors.append(f"{folder.name}: format_rules[{idx}].extensions must list '.ext' strings")
                if not isinstance(cmd, list) or not cmd or "{file}" not in cmd:
                    errors.append(f"{folder.name}: format_rules[{idx}].command must include '{{file}}'")

    sources = data.get("sources")
    if sources is not None:
        if not isinstance(sources, list) or not sources or not all(isinstance(s, str) and s.startswith(("http://", "https://")) for s in sources):
            errors.append(f"{folder.name}: 'sources' must be a non-empty list of URLs")

    last_verified = data.get("last_verified")
    if isinstance(last_verified, str):
        try:
            date.fromisoformat(last_verified)
        except ValueError:
            errors.append(f"{folder.name}: invalid ISO date '{last_verified}' in last_verified")

    paths = data.get("paths")
    if paths is not None and (not isinstance(paths, list) or not all(isinstance(x, str) and x for x in paths)):
        errors.append(f"{folder.name}: optional 'paths' must be a list of non-empty glob strings")

    practices_file = folder / "practices.md"
    if not practices_file.is_file():
        errors.append(f"{folder.name}: missing practices.md")
    else:
        non_empty_lines = [line for line in practices_file.read_text(encoding="utf-8").splitlines() if line.strip()]
        if not non_empty_lines:
            errors.append(f"{folder.name}: practices.md is empty")
        elif len(non_empty_lines) > MAX_PRACTICES_LINES:
            errors.append(f"{folder.name}: practices.md has {len(non_empty_lines)} lines (max {MAX_PRACTICES_LINES})")

    return errors


def cmd_validate(args) -> None:
    if args.profiles:
        folders = [PROFILES / name for name in args.profiles]
    else:
        folders = [p for p in sorted(PROFILES.iterdir()) if p.is_dir() and not p.name.startswith("_")] if PROFILES.is_dir() else []

    if not folders:
        print("No profiles to validate.")
        return

    all_errors = []
    for folder in folders:
        if not folder.is_dir():
            all_errors.append(f"{folder.name}: profile directory not found")
        else:
            all_errors.extend(validate_profile_folder(folder))

    if all_errors:
        for err in all_errors:
            print(f"ERROR: {err}", file=sys.stderr)
        raise SystemExit(1)

    print(f"OK: validated {len(folders)} profile(s).")


# ------------------------------------------------------------------- detection
def collect_project_files(project: Path, max_depth: int = MAX_DETECT_DEPTH) -> list:
    """Single top-down walk pruning IGNORED_DIRS up to max_depth."""
    rel_files = []
    for root, dirs, files in os.walk(project, topdown=True):
        rel_root = Path(root).relative_to(project)
        depth = 0 if rel_root == Path(".") else len(rel_root.parts)
        if depth >= max_depth:
            dirs[:] = []
        else:
            dirs[:] = sorted(d for d in dirs if d not in IGNORED_DIRS)

        prefix = "" if rel_root == Path(".") else rel_root.as_posix() + "/"
        for fname in files:
            rel_files.append(prefix + fname)
    return rel_files


def pattern_matches(rel_files: list, pattern: str) -> bool:
    if "/" in pattern:
        return any(fnmatch.fnmatch(rp, pattern) for rp in rel_files)
    return any(fnmatch.fnmatch(rp.rsplit("/", 1)[-1], pattern) for rp in rel_files)


def cmd_detect(args) -> None:
    project = Path(args.project).resolve()
    rel_files = collect_project_files(project)
    matched, known = [], []
    for folder in profile_dirs():
        p = load_profile(folder.name)
        known.append(p["stack"])
        if any(pattern_matches(rel_files, pat) for pat in p.get("detect", [])):
            matched.append(p["stack"])
    print(json.dumps({"matched": matched, "known_profiles": known}, ensure_ascii=False))


# ----------------------------------------------------------------------- apply
def _kit_hook_tag(command: str) -> str | None:
    if ".claude/hooks/" not in command:
        return None
    for script in ("guard.py", "format.py"):
        if script in command:
            return script
    return None


def merge_settings(existing: dict, wanted: dict):
    result = json.loads(json.dumps(existing))
    changes = []
    perms = result.setdefault("permissions", {})
    for key in ("allow", "deny"):
        current = perms.setdefault(key, [])
        for rule in wanted.get("permissions", {}).get(key, []):
            if rule not in current:
                current.append(rule)
                changes.append(f"permissions.{key}: {rule}")

    hooks = result.setdefault("hooks", {})
    for event, groups in wanted.get("hooks", {}).items():
        current_groups = hooks.setdefault(event, [])
        for wanted_group in groups:
            wanted_matcher = wanted_group.get("matcher")
            for wanted_hook in wanted_group.get("hooks", []):
                wanted_cmd = wanted_hook["command"]
                wanted_tag = _kit_hook_tag(wanted_cmd)

                exact_group = next(
                    (g for g in current_groups if any(h.get("command") == wanted_cmd for h in g.get("hooks", []))),
                    None,
                )
                if exact_group is not None:
                    if wanted_matcher and exact_group.get("matcher") != wanted_matcher:
                        exact_group["matcher"] = wanted_matcher
                        changes.append(f"hooks.{event} matcher -> {wanted_matcher}")
                    continue

                if wanted_tag:
                    upgraded = False
                    for g in list(current_groups):
                        group_hooks = g.get("hooks", [])
                        kept = [h for h in group_hooks if _kit_hook_tag(h.get("command", "")) != wanted_tag]
                        if len(kept) != len(group_hooks):
                            upgraded = True
                            if kept:
                                g["hooks"] = kept
                            else:
                                current_groups.remove(g)
                    if upgraded:
                        current_groups.append({**wanted_group, "hooks": [wanted_hook]})
                        changes.append(f"upgraded hooks.{event}: {wanted_cmd}")
                        continue

                current_groups.append({**wanted_group, "hooks": [wanted_hook]})
                changes.append(f"hooks.{event}: {wanted_cmd}")

    return result, changes


def build_wanted_settings(profiles: list) -> dict:
    wanted = json.loads((BASE / "settings.base.json").read_text(encoding="utf-8"))
    allow = wanted["permissions"]["allow"]
    for p in profiles:
        for rule in p.get("permissions_allow", []):
            if rule not in allow:
                allow.append(rule)
    return wanted


def render_commands(profiles: list, overrides: dict) -> str:
    lines = []
    multi = len(profiles) > 1
    for p in profiles:
        commands = {**p["commands"], **overrides.get(p["stack"], {})}
        for key, label in COMMAND_LABELS.items():
            cmd = commands.get(key)
            if cmd:
                prefix = f"[{p.get('display_name', p['stack'])}] " if multi else ""
                lines.append(f"- {prefix}{label}: `{cmd}`")
    return "\n".join(lines) or PLACEHOLDER


def resolve_rule_paths(profile: dict, ctx: dict) -> list:
    rule_paths_map = ctx.get("rule_paths", {})
    if profile["stack"] in rule_paths_map:
        return rule_paths_map[profile["stack"]] or []
    return profile.get("paths") or []


def render_practices(profiles: list, ctx: dict) -> str:
    if len(profiles) == 1:
        p = profiles[0]
        if resolve_rule_paths(p, ctx) and p["_practices"]:
            return f"See `.claude/rules/{p['stack']}.md`."
        return p["_practices"] or PLACEHOLDER

    blocks = []
    for p in profiles:
        if not p["_practices"]:
            continue
        name = p.get("display_name", p["stack"])
        if resolve_rule_paths(p, ctx):
            blocks.append(f"### {name}\nSee `.claude/rules/{p['stack']}.md`.")
        else:
            blocks.append(f"### {name}\n{p['_practices']}")
    return "\n\n".join(blocks) or PLACEHOLDER


def render_rule_file(profile: dict, paths: list) -> str:
    path_lines = "\n".join(f'  - "{pat}"' for pat in paths)
    title = profile.get("display_name", profile["stack"])
    return f"---\npaths:\n{path_lines}\n---\n\n# {title} Conventions\n\n{profile['_practices']}\n"


def write_text(path: Path, content: str, dry: bool) -> None:
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def write_non_destructive(target: Path, rel_label: str, rendered: str, dry: bool, report: list,
                          ignore_prefixes: tuple = ()) -> None:
    """Create target if missing; if it differs, write <target>.proposed and show diff in dry-run."""
    if not target.exists():
        write_text(target, rendered, dry)
        report.append(f"created   {rel_label}")
        return

    existing = target.read_text(encoding="utf-8")

    def normalize(text: str) -> str:
        if not ignore_prefixes:
            return text
        return "\n".join(l for l in text.splitlines() if not l.startswith(ignore_prefixes))

    if normalize(existing) == normalize(rendered):
        report.append(f"unchanged {rel_label} (already matches what the kit generates)")
        return

    proposed = target.with_name(target.name + ".proposed")
    proposed_label = rel_label + ".proposed"
    write_text(proposed, rendered, dry)
    report.append(f"proposed  {rel_label} already exists -> written to {proposed_label} (compare manually)")
    if dry:
        diff = list(difflib.unified_diff(
            existing.splitlines(), rendered.splitlines(),
            fromfile=rel_label, tofile=proposed_label, lineterm="",
        ))
        report.extend(f"          {line}" for line in diff)


def load_context(context_arg: str | None) -> dict:
    if not context_arg:
        return {}
    raw = sys.stdin.read() if context_arg == "-" else Path(context_arg).read_text(encoding="utf-8")
    return json.loads(raw) if raw.strip() else {}


def cmd_apply(args) -> None:
    project = Path(args.project).resolve()
    dry = args.dry_run
    report = []
    ctx = load_context(args.context)

    profiles = [load_profile(name) for name in args.profiles]
    for p in profiles:
        if age_days(p) > STALE_DAYS:
            report.append(f"⚠ profile '{p['stack']}' is stale ({age_days(p)}d): consider /claude-kit-refresh {p['stack']}")

    # 1. CLAUDE.md (never overwritten)
    template = (BASE / "CLAUDE.md.template").read_text(encoding="utf-8")
    values = {
        "PROJECT_NAME": ctx.get("name") or project.name,
        "DESCRIPTION": ctx.get("description") or PLACEHOLDER,
        "STACK": "\n".join(f"- {p.get('display_name', p['stack'])}" for p in profiles) or PLACEHOLDER,
        "COMMANDS": render_commands(profiles, ctx.get("commands_override", {})),
        "ARCHITECTURE": ctx.get("architecture") or PLACEHOLDER,
        "PRACTICES": render_practices(profiles, ctx),
        "GOTCHAS": ctx.get("gotchas") or PLACEHOLDER,
        "DATE": date.today().isoformat(),
        "PROFILES": ", ".join(p["stack"] for p in profiles) or "none",
    }
    rendered = template
    for key, value in values.items():
        rendered = rendered.replace("{{" + key + "}}", value)
    write_non_destructive(project / "CLAUDE.md", "CLAUDE.md", rendered, dry, report, GENERATED_FOOTER_PREFIXES)

    # 2. Modular .claude/rules/<stack>.md (optional, never overwritten)
    for p in profiles:
        rule_paths = resolve_rule_paths(p, ctx)
        if rule_paths and p["_practices"]:
            rule_target = project / ".claude" / "rules" / f"{p['stack']}.md"
            write_non_destructive(
                rule_target, f".claude/rules/{p['stack']}.md",
                render_rule_file(p, rule_paths), dry, report,
            )

    # 3. settings.json (additive merge + legacy kit hook upgrade)
    settings_path = project / ".claude" / "settings.json"
    wanted = build_wanted_settings(profiles)
    if settings_path.exists():
        try:
            existing = json.loads(settings_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            raise SystemExit(f"{settings_path} is not valid JSON: leaving it untouched. Fix it and re-run.")
        merged, changes = merge_settings(existing, wanted)
        if changes:
            write_text(settings_path, json.dumps(merged, indent=2, ensure_ascii=False) + "\n", dry)
            report.append(f"merged    .claude/settings.json (+{len(changes)} updates)")
            report.extend(f"           + {c}" for c in changes)
        else:
            report.append("unchanged .claude/settings.json (already up to date)")
    else:
        write_text(settings_path, json.dumps(wanted, indent=2, ensure_ascii=False) + "\n", dry)
        report.append("created   .claude/settings.json")

    # 4. Hooks (copied, never overwritten)
    for src in sorted((BASE / "hooks").iterdir()):
        if not src.is_file() or src.name.startswith("."):
            continue
        dest = project / ".claude" / "hooks" / src.name
        if not dest.exists():
            if not dry:
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, dest)
                if src.suffix == ".sh":
                    dest.chmod(dest.stat().st_mode | 0o111)
            report.append(f"created   .claude/hooks/{src.name}")
        elif dest.read_bytes() == src.read_bytes():
            report.append(f"unchanged .claude/hooks/{src.name}")
        else:
            report.append(f"skipped   .claude/hooks/{src.name} exists and differs from the kit (not overwritten)")

    # 5. kit.json (metadata + formatting rules, merged with existing)
    kit_json_path = project / ".claude" / "kit.json"
    known = {}
    if kit_json_path.exists():
        try:
            known = json.loads(kit_json_path.read_text(encoding="utf-8")).get("profiles", {})
        except json.JSONDecodeError:
            known = {}
    for p in profiles:
        known[p["stack"]] = {"last_verified": p["last_verified"]}
    format_rules = []
    for name in known:
        try:
            format_rules.extend(load_profile(name).get("format_rules", []))
        except SystemExit:
            pass  # profile deleted from kit in the meantime
    kit_json = {
        "generated_by": "claude-kit",
        "date": date.today().isoformat(),
        "profiles": known,
        "format_rules": format_rules,
    }
    write_text(kit_json_path, json.dumps(kit_json, indent=2, ensure_ascii=False) + "\n", dry)
    report.append("written   .claude/kit.json")

    # 6. .gitignore (local Claude files)
    gitignore = project / ".gitignore"
    wanted_lines = [".claude/settings.local.json", ".claude/logs/", "CLAUDE.local.md", "CLAUDE.md.proposed"]
    current = gitignore.read_text(encoding="utf-8").splitlines() if gitignore.exists() else []
    current_set = {line.strip() for line in current}
    missing = [line for line in wanted_lines if line not in current_set]
    if missing:
        text = (gitignore.read_text(encoding="utf-8").rstrip("\n") + "\n\n" if current else "")
        write_text(gitignore, text + "# Claude Code (local files)\n" + "\n".join(missing) + "\n", dry)
        report.append(f"updated   .gitignore (+{len(missing)} lines)")

    print(("[DRY-RUN: nothing was written]\n" if dry else "") + "\n".join(report))


# ------------------------------------------------------------------------ main
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("list", help="list kit profiles").set_defaults(func=cmd_list)

    p_detect = sub.add_parser("detect", help="detect known profiles in a project")
    p_detect.add_argument("--project", default=".")
    p_detect.set_defaults(func=cmd_detect)

    p_validate = sub.add_parser("validate", help="validate profile schemas and practices.md")
    p_validate.add_argument("--profiles", nargs="*", default=[], help="specific stacks to validate (default: all)")
    p_validate.set_defaults(func=cmd_validate)

    p_apply = sub.add_parser("apply", help="generate config in a project")
    p_apply.add_argument("--project", default=".")
    p_apply.add_argument("--profiles", nargs="*", default=[], help="stack names (e.g., python angular)")
    p_apply.add_argument("--context", help="JSON path or '-' for stdin: name, description, architecture, gotchas, commands_override, rule_paths")
    p_apply.add_argument("--dry-run", action="store_true")
    p_apply.set_defaults(func=cmd_apply)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
