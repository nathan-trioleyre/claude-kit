def profile_dirs() -> list:
    if not PROFILES.is_dir():
        return []
    return sorted(
        p for p in PROFILES.iterdir()
        if p.is_dir() and not p.name.startswith("_") and (p / "profile.json").is_file()
    )


def load_profile(name: str) -> dict:
    folder = PROFILES / name
    file = folder / "profile.json"
    if not file.is_file():
        raise SystemExit(f"Profile not found: {name} (expected: {file})")
    data = json.loads(file.read_text(encoding="utf-8"))
    missing = [k for k in ("stack", "commands", "last_verified") if k not in data]
    if missing:
        raise SystemExit(f"Invalid profile {name}, missing keys: {', '.join(missing)}")
    practices = folder / "practices.md"
    data["_practices"] = practices.read_text(encoding="utf-8").strip() if practices.is_file() else ""
    return data


def age_days(profile: dict) -> int:
    try:
        return (date.today() - date.fromisoformat(profile["last_verified"])).days
    except ValueError:
        return 10**6  # unreadable date: treated as stale


def cmd_list(_args) -> None:
    out = []
    for folder in profile_dirs():
        p = load_profile(folder.name)
        age = age_days(p)
        out.append({
            "stack": p["stack"],
            "display_name": p.get("display_name", p["stack"]),
            "last_verified": p["last_verified"],
            "age_days": age,
            "stale": age > STALE_DAYS,
        })
    print(json.dumps(out, ensure_ascii=False, indent=2))


