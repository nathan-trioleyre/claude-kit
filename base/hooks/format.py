#!/usr/bin/env python3
"""PostToolUse hook: automatically formats and fast-lints a file after Write/Edit/NotebookEdit.

Rules come from .claude/kit.json (generated by /claude-kit from stack
profiles), so this script is identical across all languages.

Always exits 0. Lint findings are surfaced to Claude through the PostToolUse JSON
contract on stdout ({"decision": "block", "reason": ...}), truncated to MAX_LINT_LINES.
Formatter failures, timeouts and missing tool binaries stay silent for Claude
(formatter failures are only echoed on stderr, visible in verbose mode).
All rules share one deadline that stays below the hook timeout in settings.json.
# claude-kit-hook-version: 5
"""
import fnmatch
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

TOTAL_BUDGET_S = 25.0  # hook timeout in settings.base.json is 30s
LINT_TIMEOUT_S = 10.0
FORMAT_TIMEOUT_S = 20.0
MAX_LINT_LINES = 40
MAX_LINT_CHARS = 4000


def _utf8_stdio() -> None:
    for stream in (sys.stdin, sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


def resolve_executable(cmd_name: str, file_path: Path, project: Path) -> str | None:
    """Find executable in project-local node_modules/.bin or .venv before global PATH."""
    if os.path.isabs(cmd_name) and Path(cmd_name).is_file():
        return cmd_name

    candidates = []
    # Walk from edited file directory up to project root for monorepo node_modules/.bin
    cur = file_path.resolve().parent
    proj_resolved = project.resolve()
    while True:
        candidates.append(cur / "node_modules" / ".bin")
        if cur == proj_resolved or cur.parent == cur:
            break
        cur = cur.parent

    for venv_name in (".venv", "venv"):
        candidates.append(proj_resolved / venv_name / "Scripts")
        candidates.append(proj_resolved / venv_name / "bin")

    for bin_dir in candidates:
        if bin_dir.is_dir():
            found = shutil.which(cmd_name, path=str(bin_dir))
            if found:
                return found

    return shutil.which(cmd_name)


def _rule_matches(rule: dict, file_path: Path, file_path_str: str) -> bool:
    exts = rule.get("extensions") or []
    if any(fnmatch.fnmatch(file_path_str.lower(), "*" + ext.lower()) for ext in exts):
        return True
    fnames = rule.get("filenames") or []
    name_low = file_path.name.lower()
    return any(fnmatch.fnmatch(name_low, pat.lower()) for pat in fnames)


def _run_rules(rules: list, file_path: Path, file_path_str: str, project: Path,
               *, timeout: float, deadline: float) -> list:
    """Run every matching rule; return [(tool, output_lines)] for the ones that failed."""
    failures = []
    for rule in rules:
        if not _rule_matches(rule, file_path, file_path_str):
            continue
        remaining = deadline - time.monotonic()
        if remaining < 1:
            break
        cmd = [part.replace("{file}", file_path_str) for part in rule["command"]]
        exe = resolve_executable(cmd[0], file_path, project)
        if not exe:
            continue
        try:
            res = subprocess.run([exe, *cmd[1:]], cwd=project, timeout=min(timeout, remaining),
                                 capture_output=True, text=True, encoding="utf-8", errors="replace")
        except (subprocess.TimeoutExpired, OSError):
            continue  # slow or broken tool: skip it, keep going with the next rule
        if res.returncode != 0:
            lines = [ln for ln in ((res.stdout or "") + "\n" + (res.stderr or "")).splitlines() if ln.strip()]
            failures.append((cmd[0], lines or [f"exit {res.returncode}"]))
    return failures


def _lint_reason(failures: list, file_path: Path) -> str:
    out = []
    for tool, lines in failures:
        out.append(f"{tool} reported issues in {file_path.name}:")
        out.extend(lines)
    if len(out) > MAX_LINT_LINES:
        extra = len(out) - MAX_LINT_LINES
        out = out[:MAX_LINT_LINES] + [f"... ({extra} more lines truncated)"]
    text = "\n".join(out)
    if len(text) > MAX_LINT_CHARS:
        text = text[:MAX_LINT_CHARS] + "\n... (truncated)"
    return f"Lint findings after editing {file_path.name} (format.py lint_rules). Fix them:\n{text}"


def main() -> None:
    _utf8_stdio()
    debug = bool(os.environ.get("CLAUDE_KIT_DEBUG"))
    deadline = time.monotonic() + TOTAL_BUDGET_S
    try:
        payload = json.load(sys.stdin)
        tool_input = payload.get("tool_input") or {}
        file_path_str = tool_input.get("file_path") or tool_input.get("notebook_path") or ""
        if not file_path_str:
            return
        file_path = Path(file_path_str)
        if not file_path.is_file():
            return

        project = Path(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or ".")
        config = json.loads((project / ".claude" / "kit.json").read_text(encoding="utf-8"))

        lint_failures = _run_rules(config.get("lint_rules", []), file_path, file_path_str, project,
                                   timeout=LINT_TIMEOUT_S, deadline=deadline)
        fmt_failures = _run_rules(config.get("format_rules", []), file_path, file_path_str, project,
                                  timeout=FORMAT_TIMEOUT_S, deadline=deadline)
        for tool, lines in fmt_failures:
            print(f"format.py: {tool} failed on {file_path.name}: {lines[-1]}", file=sys.stderr)
        if lint_failures:
            print(json.dumps({"decision": "block", "reason": _lint_reason(lint_failures, file_path)}))
    except Exception as exc:
        if debug:
            print(f"format.py debug: {exc}", file=sys.stderr)
        return


if __name__ == "__main__":
    main()
    sys.exit(0)
