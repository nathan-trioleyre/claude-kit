#!/usr/bin/env python3
"""PostToolUse hook: automatically formats a file after Write/Edit.

Rules come from .claude/kit.json (generated by /claude-kit from stack
profiles), so this script is identical across all languages.
It never blocks Claude (always exits 0), but reports formatter errors on stderr.
# claude-kit-hook-version: 3
"""
import fnmatch
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path


def resolve_executable(cmd_name: str, file_path: Path, project: Path) -> str | None:
    """Find executable in project-local node_modules/.bin or .venv before global PATH."""
    if os.path.isabs(cmd_name) and Path(cmd_name).is_file():
        return cmd_name

    candidates = []
    # Walk from edited file directory up to project root for monorepo node_modules/.bin
    cur = file_path.resolve().parent
    proj_resolved = project.resolve()
    while True:
        candidates.append(cur / "node_modules" / ".bin")
        if cur == proj_resolved or cur.parent == cur:
            break
        cur = cur.parent

    for venv_name in (".venv", "venv"):
        candidates.append(proj_resolved / venv_name / "Scripts")
        candidates.append(proj_resolved / venv_name / "bin")

    for bin_dir in candidates:
        if bin_dir.is_dir():
            found = shutil.which(cmd_name, path=str(bin_dir))
            if found:
                return found

    return shutil.which(cmd_name)


def main() -> None:
    debug = bool(os.environ.get("CLAUDE_KIT_DEBUG"))
    try:
        payload = json.load(sys.stdin)
        file_path_str = (payload.get("tool_input") or {}).get("file_path", "")
        if not file_path_str:
            return
        file_path = Path(file_path_str)
        if not file_path.is_file():
            return

        project = Path(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or ".")
        config = json.loads((project / ".claude" / "kit.json").read_text(encoding="utf-8"))

        for rule in config.get("format_rules", []):
            if any(fnmatch.fnmatch(file_path_str.lower(), "*" + ext.lower()) for ext in rule["extensions"]):
                cmd = [part.replace("{file}", file_path_str) for part in rule["command"]]
                exe = resolve_executable(cmd[0], file_path, project)
                if exe:
                    res = subprocess.run([exe, *cmd[1:]], cwd=project, timeout=20,
                                         capture_output=True, text=True)
                    if res.returncode != 0:
                        msg = (res.stderr or res.stdout or "").strip().splitlines()
                        detail = msg[-1] if msg else f"exit {res.returncode}"
                        print(f"format.py: {cmd[0]} failed on {file_path.name}: {detail}", file=sys.stderr)
    except Exception as exc:
        if debug:
            print(f"format.py debug: {exc}", file=sys.stderr)
        return


if __name__ == "__main__":
    main()
    sys.exit(0)
