    def test_dry_run_shows_diff_for_existing_claude_md_and_upgrades_legacy_hooks(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit"
            copy_kit(kit_copy)
            make_profile(kit_copy, "python")
            apply_bin = kit_copy / "skills" / "claude-kit" / "scripts" / "apply.py"

            proj = t / "existing"
            (proj / ".claude").mkdir(parents=True)
            (proj / "CLAUDE.md").write_text("# Old Title\nCustom user notes.\n", encoding="utf-8")
            # Legacy settings with old guard command and custom user hook
            (proj / ".claude" / "settings.json").write_text(json.dumps({
                "permissions": {"allow": ["Read"], "deny": []},
                "hooks": {
                    "PreToolUse": [
                        {"matcher": "Bash", "hooks": [{"type": "command", "command": "python \"$CLAUDE_PROJECT_DIR/.claude/hooks/guard.py\""}]},
                        {"matcher": "Bash", "hooks": [{"type": "command", "command": "echo custom-hook"}]},
                    ]
                }
            }), encoding="utf-8")

            dry = subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python", "--dry-run"],
                text=True,
            )
            self.assertIn("--- CLAUDE.md", dry)
            self.assertIn("+++ CLAUDE.md.proposed", dry)
            self.assertFalse((proj / "CLAUDE.md.proposed").exists())

            subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python"],
                text=True,
            )
            merged = json.loads((proj / ".claude" / "settings.json").read_text(encoding="utf-8"))
            pre_groups = merged["hooks"]["PreToolUse"]
            cmds = [h["command"] for g in pre_groups for h in g["hooks"]]
            self.assertIn("echo custom-hook", cmds)
            self.assertFalse(any("python \"$CLAUDE_PROJECT_DIR/.claude/hooks/guard.py\"" == c for c in cmds))
            self.assertTrue(any("run-hook.sh" in c and "guard.py" in c for c in cmds))

