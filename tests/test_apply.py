def make_profile(kit_root: Path, stack: str = "python", *, detect=None, paths=None, practices="- Use pytest.\n",
                 permissions_allow=None, last_verified=None) -> None:
    prof = kit_root / "profiles" / stack
    prof.mkdir(parents=True, exist_ok=True)
    data = {
        "stack": stack,
        "display_name": f"{stack.title()} Stack",
        "detect": detect or ["pyproject.toml"],
        "commands": {
            "install": "pip install -e .",
            "dev": None,
            "test": "pytest",
            "lint": "ruff check .",
            "format": "ruff format .",
            "build": None,
            "verify": "pytest && ruff check .",
        },
        "permissions_allow": permissions_allow if permissions_allow is not None else ["Bash(pytest *)"],
        "format_rules": [{"extensions": [".py"], "command": ["ruff", "format", "{file}"]}],
        "sources": ["https://docs.python.org/3/"],
        "last_verified": last_verified or date.today().isoformat(),
    }
    if paths is not None:
        data["paths"] = paths
    (prof / "profile.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (prof / "practices.md").write_text(practices, encoding="utf-8")


def copy_kit(dest: Path) -> None:
    """Copy the kit without tests/.git and WITHOUT the starter profiles (tests build their own)."""
    shutil.copytree(KIT, dest, ignore=shutil.ignore_patterns("tests", "__pycache__", ".git"))
    for folder in (dest / "profiles").iterdir():
        if folder.is_dir() and not folder.name.startswith("_"):
            shutil.rmtree(folder)


def run_apply(apply_bin: Path, *args, input=None, check=True):
    return subprocess.run([sys.executable, str(apply_bin), *args], input=input, text=True,
                          capture_output=True, check=check)


