import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from datetime import date
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
APPLY = KIT / "skills" / "claude-kit" / "scripts" / "apply.py"


def make_profile(kit_root: Path, stack: str = "python", *, detect=None, paths=None, practices="- Use pytest.\n",
                 permissions_allow=None, last_verified=None) -> None:
    prof = kit_root / "profiles" / stack
    prof.mkdir(parents=True, exist_ok=True)
    data = {
        "stack": stack,
        "display_name": f"{stack.title()} Stack",
        "detect": detect or ["pyproject.toml"],
        "commands": {
            "install": "pip install -e .",
            "dev": None,
            "test": "pytest",
            "lint": "ruff check .",
            "format": "ruff format .",
            "build": None,
            "verify": "pytest && ruff check .",
        },
        "permissions_allow": permissions_allow if permissions_allow is not None else ["Bash(pytest *)"],
        "format_rules": [{"extensions": [".py"], "command": ["ruff", "format", "{file}"]}],
        "sources": ["https://docs.python.org/3/"],
        "last_verified": last_verified or date.today().isoformat(),
    }
    if paths is not None:
        data["paths"] = paths
    (prof / "profile.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (prof / "practices.md").write_text(practices, encoding="utf-8")


class TestApply(unittest.TestCase):
    def test_copied_apply_resolves_kit_via_config(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit-copy"
            shutil.copytree(KIT, kit_copy, ignore=shutil.ignore_patterns("tests", "__pycache__"))
            make_profile(kit_copy, "python")

            home_dir = t / "home"
            claude_dir = home_dir / ".claude"
            subprocess.run(
                [sys.executable, str(kit_copy / "install.py"), "--claude-dir", str(claude_dir)],
                capture_output=True, check=True,
            )
            copied_apply = claude_dir / "skills" / "claude-kit" / "scripts" / "apply.py"
            env = {**os.environ, "HOME": str(home_dir), "USERPROFILE": str(home_dir)}
            out = subprocess.check_output([sys.executable, str(copied_apply), "list"], text=True, env=env)
            profiles = json.loads(out)
            self.assertEqual([p["stack"] for p in profiles], ["python"])

    def test_detect_finds_depth3_and_skips_ignored_dirs(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit"
            shutil.copytree(KIT, kit_copy, ignore=shutil.ignore_patterns("tests", "__pycache__"))
            make_profile(kit_copy, "python", detect=["pyproject.toml"])
            make_profile(kit_copy, "node", detect=["package.json"])

            proj = t / "monorepo"
            (proj / "packages" / "services" / "api").mkdir(parents=True)
            (proj / "packages" / "services" / "api" / "pyproject.toml").write_text("[project]\n")
            (proj / "node_modules" / "some-pkg").mkdir(parents=True)
            (proj / "node_modules" / "some-pkg" / "package.json").write_text("{}")

            out = subprocess.check_output(
                [sys.executable, str(kit_copy / "skills" / "claude-kit" / "scripts" / "apply.py"), "detect", "--project", str(proj)],
                text=True,
            )
            data = json.loads(out)
            self.assertEqual(data["matched"], ["python"])

    def test_apply_empty_profiles_and_stdin_context(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            proj = t / "blank-proj"
            proj.mkdir()
            ctx = json.dumps({"name": "BlankApp", "description": "No known profile yet."})
            out = subprocess.check_output(
                [sys.executable, str(APPLY), "apply", "--project", str(proj), "--context", "-"],
                input=ctx, text=True,
            )
            self.assertIn("created   CLAUDE.md", out)
            claude_md = (proj / "CLAUDE.md").read_text(encoding="utf-8")
            self.assertIn("# BlankApp", claude_md)
            self.assertIn("Generated by claude-kit on", claude_md)
            gitignore = (proj / ".gitignore").read_text(encoding="utf-8")
            self.assertIn("CLAUDE.local.md", gitignore)
            self.assertIn("CLAUDE.md.proposed", gitignore)

    def test_dry_run_shows_diff_for_existing_claude_md_and_upgrades_legacy_hooks(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit"
            shutil.copytree(KIT, kit_copy, ignore=shutil.ignore_patterns("tests", "__pycache__"))
            make_profile(kit_copy, "python")
            apply_bin = kit_copy / "skills" / "claude-kit" / "scripts" / "apply.py"

            proj = t / "existing"
            (proj / ".claude").mkdir(parents=True)
            (proj / "CLAUDE.md").write_text("# Old Title\nCustom user notes.\n", encoding="utf-8")
            # Legacy settings with old guard command and custom user hook
            (proj / ".claude" / "settings.json").write_text(json.dumps({
                "permissions": {"allow": ["Read"], "deny": []},
                "hooks": {
                    "PreToolUse": [
                        {"matcher": "Bash", "hooks": [{"type": "command", "command": "python \"$CLAUDE_PROJECT_DIR/.claude/hooks/guard.py\""}]},
                        {"matcher": "Bash", "hooks": [{"type": "command", "command": "echo custom-hook"}]},
                    ]
                }
            }), encoding="utf-8")

            dry = subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python", "--dry-run"],
                text=True,
            )
            self.assertIn("--- CLAUDE.md", dry)
            self.assertIn("+++ CLAUDE.md.proposed", dry)
            self.assertFalse((proj / "CLAUDE.md.proposed").exists())

            subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python"],
                text=True,
            )
            merged = json.loads((proj / ".claude" / "settings.json").read_text(encoding="utf-8"))
            pre_groups = merged["hooks"]["PreToolUse"]
            cmds = [h["command"] for g in pre_groups for h in g["hooks"]]
            self.assertIn("echo custom-hook", cmds)
            self.assertFalse(any("python \"$CLAUDE_PROJECT_DIR/.claude/hooks/guard.py\"" == c for c in cmds))
            self.assertTrue(any("run-hook.sh" in c and "guard.py" in c for c in cmds))

    def test_modular_rules_generation_and_non_overwrite(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit"
            shutil.copytree(KIT, kit_copy, ignore=shutil.ignore_patterns("tests", "__pycache__"))
            make_profile(kit_copy, "python", paths=["backend/**/*.py"], practices="- Use ruff.\n")
            apply_bin = kit_copy / "skills" / "claude-kit" / "scripts" / "apply.py"

            proj = t / "mono"
            proj.mkdir()
            subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python"],
                text=True,
            )
            rule_file = proj / ".claude" / "rules" / "python.md"
            self.assertTrue(rule_file.is_file())
            content = rule_file.read_text(encoding="utf-8")
            self.assertIn("paths:", content)
            self.assertIn("backend/**/*.py", content)
            self.assertIn("Use ruff.", content)

            # Customize rule file and re-run: must write .proposed, not overwrite
            rule_file.write_text("# Custom rule\n", encoding="utf-8")
            subprocess.check_output(
                [sys.executable, str(apply_bin), "apply", "--project", str(proj), "--profiles", "python"],
                text=True,
            )
            self.assertEqual(rule_file.read_text(encoding="utf-8"), "# Custom rule\n")
            self.assertTrue((proj / ".claude" / "rules" / "python.md.proposed").is_file())

    def test_validate_subcommand(self):
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            kit_copy = t / "kit"
            shutil.copytree(KIT, kit_copy, ignore=shutil.ignore_patterns("tests", "__pycache__"))
            make_profile(kit_copy, "python")
            apply_bin = kit_copy / "skills" / "claude-kit" / "scripts" / "apply.py"

            ok = subprocess.run([sys.executable, str(apply_bin), "validate"], capture_output=True, text=True)
            self.assertEqual(ok.returncode, 0, ok.stdout + ok.stderr)

            # Break profile with dangerous wildcard permission & >15 lines practices
            too_long = "\n".join(f"- Practice {i}" for i in range(16)) + "\n"
            make_profile(kit_copy, "badstack", permissions_allow=["Bash(*)"], practices=too_long, last_verified="not-a-date")
            bad = subprocess.run([sys.executable, str(apply_bin), "validate"], capture_output=True, text=True)
            self.assertNotEqual(bad.returncode, 0)
            self.assertIn("Bash(*)", bad.stdout + bad.stderr)
            self.assertIn("15", bad.stdout + bad.stderr)


if __name__ == "__main__":
    unittest.main()
